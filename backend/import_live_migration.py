"""Restore and verify a private export into the isolated WAREHOUSE_LIVE schema."""
import argparse
from collections import Counter
from decimal import Decimal
import hashlib
import json
import os
from pathlib import Path

import oracledb
from export_live_migration import checksum, decode, encode, quote
from run_sql import iter_statements


def canonical(row):
    values = []
    for value in row:
        if hasattr(value, "read"):
            value = value.read()
        if isinstance(value, (Decimal, int)) and not isinstance(value, bool):
            text = format(Decimal(value), "f")
            if "." in text:
                text = text.rstrip("0").rstrip(".")
            values.append(["number", "0" if Decimal(value) == 0 else text])
        else:
            values.append(encode(value))
    data = json.dumps(values, ensure_ascii=False, allow_nan=False, separators=(",", ":"))
    return hashlib.sha256(data.encode("utf-8")).hexdigest()


def safe_path(root, name):
    path = (root / name).resolve()
    if root not in path.parents:
        raise RuntimeError("Bundle path escapes its directory.")
    return path


def execute_file(cur, path):
    for filename, line, sql in iter_statements(str(path)):
        try:
            cur.execute(sql)
        except Exception as exc:
            # Report location only: a SQL statement may contain private values.
            raise RuntimeError(f"Schema failure in {Path(filename).name}:{line}: {exc}") from exc


def bind_type(dtype):
    if dtype == "BLOB":
        return oracledb.DB_TYPE_BLOB
    if dtype == "CLOB":
        return oracledb.DB_TYPE_CLOB
    if dtype == "NCLOB":
        return oracledb.DB_TYPE_NCLOB
    if dtype == "NUMBER":
        return oracledb.DB_TYPE_NUMBER
    if dtype == "DATE":
        return oracledb.DB_TYPE_DATE
    if dtype.startswith("TIMESTAMP"):
        if "WITH LOCAL TIME ZONE" in dtype:
            return oracledb.DB_TYPE_TIMESTAMP_LTZ
        if "WITH TIME ZONE" in dtype:
            return oracledb.DB_TYPE_TIMESTAMP_TZ
        return oracledb.DB_TYPE_TIMESTAMP
    if dtype == "NVARCHAR2":
        return oracledb.DB_TYPE_NVARCHAR
    if dtype == "NCHAR":
        return oracledb.DB_TYPE_NCHAR
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle", required=True)
    args = parser.parse_args()
    root = Path(args.bundle).resolve()
    manifest = json.loads((root / "manifest.json").read_text(encoding="utf-8-sig"))
    if manifest.get("format") != 1:
        raise RuntimeError("Unknown bundle format.")
    for filename, digest in manifest["files"].items():
        if checksum(safe_path(root, filename)) != digest:
            raise RuntimeError(f"Checksum mismatch: {filename}")
    for table in manifest["tables"]:
        if table["file"] not in manifest["files"]:
            raise RuntimeError("Table data is missing from checksum manifest.")
    for filename in ["01_sequences.sql", "02_tables.sql", "03_constraints.sql",
                     "04_foreign_keys.sql", "05_indexes.sql", "06_triggers.sql"]:
        if f"schema/{filename}" not in manifest["files"]:
            raise RuntimeError(f"Schema file missing from checksum manifest: {filename}")
    print("All bundle checksums verified.", flush=True)

    user = os.environ["ORACLE_USER"]
    if user.upper() != "WAREHOUSE_LIVE":
        raise RuntimeError("Only isolated WAREHOUSE_LIVE schema is allowed.")
    oracledb.defaults.fetch_lobs = False
    oracledb.defaults.fetch_decimals = True
    with oracledb.connect(
        user=user, password=os.environ["ORACLE_PASSWORD"], dsn=os.environ["ORACLE_DSN"]
    ) as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT USER FROM dual")
            if cur.fetchone()[0] != "WAREHOUSE_LIVE":
                raise RuntimeError("Unexpected connected schema.")
            cur.execute("SELECT COUNT(*) FROM user_tables")
            if cur.fetchone()[0]:
                raise RuntimeError("Target schema already has tables; refusing to overwrite.")
            for filename in ["01_sequences.sql", "02_tables.sql", "03_constraints.sql",
                             "05_indexes.sql", "07_comments.sql"]:
                execute_file(cur, root / "schema" / filename)
                print(f"Applied {filename}", flush=True)

            cur.execute(
                "SELECT table_name, column_name, generation_type FROM user_tab_identity_cols"
            )
            identities = cur.fetchall()
            for table, column, generation in identities:
                if generation == "ALWAYS":
                    cur.execute(
                        f"ALTER TABLE {quote(table)} MODIFY "
                        f"({quote(column)} GENERATED BY DEFAULT AS IDENTITY)"
                    )

            for table in manifest["tables"]:
                name = table["name"]
                columns = table["columns"]
                sql = f"INSERT INTO {quote(name)} ("
                sql += ", ".join(quote(col["name"]) for col in columns)
                sql += ") VALUES (" + ", ".join(f":{i+1}" for i in range(len(columns))) + ")"
                cur.setinputsizes(*[bind_type(col["type"]) for col in columns])
                count = 0
                batch = []
                with safe_path(root, table["file"]).open(encoding="utf-8") as handle:
                    for line in handle:
                        values = [decode(item) for item in json.loads(line)]
                        if len(values) != len(columns):
                            raise RuntimeError(f"{name}: column-count mismatch.")
                        batch.append(values)
                        if len(batch) == 50:
                            cur.executemany(sql, batch)
                            count += len(batch)
                            batch.clear()
                    if batch:
                        cur.executemany(sql, batch)
                        count += len(batch)
                if count != table["rows"]:
                    raise RuntimeError(f"{name}: imported row-count mismatch.")
                print(f"Loaded {name}: {count} rows", flush=True)

            # Compare every stored value, using a multiset so physical row order is irrelevant.
            for table in manifest["tables"]:
                expected = Counter()
                with safe_path(root, table["file"]).open(encoding="utf-8") as handle:
                    for line in handle:
                        expected[canonical([decode(item) for item in json.loads(line)])] += 1
                cur.execute(
                    "SELECT " + ", ".join(quote(c["name"]) for c in table["columns"])
                    + " FROM " + quote(table["name"])
                )
                actual = Counter(canonical(row) for row in cur)
                if actual != expected:
                    raise RuntimeError(f"{table['name']}: stored-content verification failed.")
                print(f"Verified {table['name']}: {sum(actual.values())} rows and contents", flush=True)
            conn.commit()

            execute_file(cur, root / "schema" / "04_foreign_keys.sql")
            for table, column, generation in identities:
                cur.execute(
                    f"ALTER TABLE {quote(table)} MODIFY "
                    f"({quote(column)} GENERATED {generation} AS IDENTITY (START WITH LIMIT VALUE))"
                )
            for sequence in manifest.get("sequences", []):
                cur.execute(
                    f"ALTER SEQUENCE {quote(sequence['name'])} RESTART START WITH "
                    + str(int(sequence["next_value"]))
                )

            execute_file(cur, root / "schema" / "06_triggers.sql")

            cur.execute(
                "SELECT object_name, object_type FROM user_objects WHERE status='INVALID'"
            )
            invalid = cur.fetchall()
            if invalid:
                raise RuntimeError(f"Invalid objects after restore: {invalid}")
            cur.execute(
                "SELECT constraint_name FROM user_constraints "
                "WHERE status <> 'ENABLED' OR validated <> 'VALIDATED'"
            )
            bad = cur.fetchall()
            if bad:
                raise RuntimeError(f"Unvalidated or disabled constraints: {bad}")

    total = sum(table["rows"] for table in manifest["tables"])
    print(f"RESTORE VERIFIED: {len(manifest['tables'])} tables, {total} rows.", flush=True)
    print("Attachments, password hashes, relationships and ID generators verified.", flush=True)
    print("Backend has NOT been switched.", flush=True)


if __name__ == "__main__":
    main()

